"""Generate ghouls_data.h: the original's data, each array at its original address."""

from header import cli
from sidtrace import psid_parts

BLOCK_SRC, BLOCK_DST, BLOCK_LEN, BLOCKS = 0x29E7, 0x29FB, 0x2A30, 10
TABLES_ORG, TABLES_END = 0x6CB7, 0x730E
# music init's copy destinations, in address order
COPIES = ("music", "patterns")
HR_FREQ, HR_STRIDE = 0x6BDA, 0x1B
# {array: original addresses} of the data the original keeps in gaps of its code
GAPS = {
    "pulse_default": range(0x6A05, 0x6A0B),
    "stack": range(0x6B1F, 0x6B31),
    "hr_freq": tuple(HR_FREQ + HR_STRIDE * v + k for v in range(3) for k in range(2)),
}


def _blocks(load, image):
    """(source, destination, length) of each copy block of music init."""

    def word(a):
        return image[a - load] | image[a + 1 - load] << 8

    return [
        (word(BLOCK_SRC + 2 * b), word(BLOCK_DST + 2 * b), word(BLOCK_LEN + 2 * b))
        for b in range(BLOCKS)
    ]


def _merge(spans):
    """Union of half-open spans, as sorted disjoint spans."""
    out = []
    for lo, hi in sorted(spans):
        if out and lo <= out[-1][1]:
            out[-1][1] = max(out[-1][1], hi)
        else:
            out.append([lo, hi])
    return [tuple(s) for s in out]


def held(psid):
    """{array: original addresses}: block tables and sources, the data in gaps of the code,
    effect and frequency tables, and the copy destinations."""
    load, _, _, image = psid_parts(psid)
    blocks = _blocks(load, image)
    end = max(s + n for s, _, n in blocks)
    copies = _merge((d, d + n) for _, d, n in blocks)
    return {
        "blocks": range(BLOCK_SRC, end),
        **GAPS,
        "tables": range(TABLES_ORG, TABLES_END),
        **{k: range(lo, hi) for k, (lo, hi) in zip(COPIES, copies, strict=True)},
    }


def named(_psid):
    """{what the C has instead: original addresses} of the data it does not hold."""
    return {"effect_init's voice index": range(0x622E, 0x6234)}


def generate(psid):
    """Header text: per array its first address and the image's bytes, or its length for a
    copy destination."""
    load, _, _, image = psid_parts(psid)
    lines = ["/* generated by gen_ghouls.py */"]
    for name, addrs in held(psid).items():
        lines.append(f"#define {name.upper()}_ORG 0x{addrs[0]:04x}")
        if name in COPIES:
            lines.append(f"#define {name.upper()}_LEN 0x{len(addrs):04x}")
        else:
            body = ",".join(f"0x{image[a - load]:02x}" for a in addrs)
            lines.append(f"#define {name.upper()}_DATA {body}")
    return "\n".join(lines) + "\n"


def main(argv=None):
    """CLI entry point."""
    cli(generate, __doc__, argv)


if __name__ == "__main__":
    main()
