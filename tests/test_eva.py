def tail(count, eva_errors=0, kinds="4 alarms by kind"):
    """The analysis summary of a log reporting `count` alarms."""
    alarms = (
        f"  {count} alarms generated by the analysis:\n       {kinds}\n"
        if count
        else "  0 alarms generated by the analysis.\n"
    )
    return (
        "[eva:summary] ====== ANALYSIS SUMMARY ======\n"
        "  16 functions analyzed (out of 17): 94% coverage.\n"
        "  In these functions, 356 statements reached (out of 367): 97% coverage.\n"
        "  Some errors and warnings have been raised during the analysis:\n"
        f"    by the Eva analyzer:      {eva_errors} errors    0 warnings\n"
        "    by the Frama-C kernel:    0 errors    1 warning\n" + alarms
    )


LOG = HEAD + STATES + tail(4)


def test_harness_includes_the_tune_on_the_host():
    """The harness defines CGEN_HOST before it includes the tune's C, inits any song and
    plays any number of times, every I/O read any byte."""
    text = eva.harness("emomyst")
    assert "@TUNE@" not in text
    assert text.index("#define CGEN_HOST") < text.index('#include "emomyst.c"')
    assert "tune_init(Frama_C_unsigned_char_interval(0, 255))" in text
    assert "while (Frama_C_nondet(0, 1))" in text
    assert "return Frama_C_unsigned_char_interval(0, 255);" in text


def test_harness_template_needs_placeholder(tmp_path):
    """A template that cannot name the tune is an error, not a harness of nothing."""
    bad = tmp_path / "h.c"
    bad.write_text('#include "x.c"\n')
    with pytest.raises(ValueError):
        eva.harness("commando", bad)


def test_alarms_single_and_multi_line():
    """Each alarm's file, line, kind and assertion, a multi-line assertion collapsed; a
    bottom without alarms is not one."""
    got = eva.alarms(LOG.splitlines())
    assert [(a["file"], a["line"]) for a in got] == [
        ("t.c", 69),
        ("t.c", 1117),
        ("t.c", 834),
        ("t.c", 200),
    ]
    assert [a["kind"] for a in got] == [
        "accessing out of bounds index",
        "accessing out of bounds index",
        "invalid LHS operand for left shift",
        "out of bounds read",
    ]
    assert got[0]["assertion"] == "(int)(0x789 + (int)v23) < 2031"
    assert got[1]["assertion"].startswith("(int)((int)((uint16_t)((int)((int)S_7CC |")
    assert got[1]["assertion"].endswith(") < 2529")
    assert "  " not in got[1]["assertion"]
    assert got[3]["assertion"] == "\\valid_read(table_45C + v24)"


def test_parse_complete_log():
    """A finished log's count, coverage, errors, trap reached and play returning."""
    report = eva.parse(LOG)
    assert report["count"] == 4
    assert report["coverage"] == {"functions": [16, 17], "statements": [356, 367]}
    assert report["errors"] == {"Eva analyzer": 0, "Frama-C kernel": 0}
    assert report["trap_reached"] and report["play_returns"]
    eva.check(report)


def test_parse_zero_alarms_trap_unreachable():
    """The summary's zero form, and trap unreachable when it has no final state."""
    states = STATES.replace(
        "[eva:final-states] Values at end of function trap:\n  NON TERMINATING FUNCTION\n",
        "",
    )
    report = eva.parse(states + tail(0))
    assert report["count"] == 0 and not report["alarms"]
    assert not report["trap_reached"]
    eva.check(report)


@pytest.mark.parametrize(
    "log, why",
    [
        (HEAD, "no analysis summary"),
        (HEAD + STATES + tail(4, eva_errors=1), "errors"),
        (HEAD + STATES + tail(5), "summary counts 5 alarms, log lists 4"),
        (
            HEAD
            + STATES.replace("  R0[0] ∈ {39; 103; 230}", "  NON TERMINATING FUNCTION")
            + tail(4),
            "tune_play never returns",
        ),
        (HEAD + tail(4), "tune_play never returns"),
    ],
)
def test_check_rejects_incomplete(log, why):
    """A truncated log, an analyzer error, a count unlike the alarms listed and a play that
    never returns are no result."""
    with pytest.raises(eva.EvaError, match=why):
        eva.check(eva.parse(log))


def sources(src, tune="t"):
    """A generated <tune>.c and .h under `src`."""
    src.mkdir(parents=True, exist_ok=True)
    (src / f"{tune}.c").write_text(f'#include "{tune}.h"\nint x;\n')
    (src / f"{tune}.h").write_text("#include <stdint.h>\n")


def test_stage_copies_sources_and_driver(tmp_path):
    """The work directory holds the tune's C, its header, driver.h and the harness."""
    sources(tmp_path / "src")
    work = eva.stage("t", tmp_path / "src", tmp_path / "out")
    assert work == tmp_path / "out" / "t"
    assert sorted(p.name for p in work.iterdir()) == [
        "driver.h",
        "harness.c",
        "t.c",
        "t.h",
    ]
    assert '#include "t.c"' in (work / "harness.c").read_text()


def test_stage_missing_source(tmp_path):
    """A tune not generated is an error naming the file."""
    with pytest.raises(FileNotFoundError, match="t.c"):
        eva.stage("t", tmp_path / "src", tmp_path / "out")


def test_command_container_and_local(tmp_path):
    """The container is named, CPU-limited, run as the caller with the work directory
    mounted at its own path; a local frama-c takes the same arguments."""
    argv = eva.command(tmp_path, "n", image="img", cpus=2)
    assert argv[:5] == ["docker", "run", "--rm", "--name", "n"]
    assert "--cpus=2" in argv
    assert argv[argv.index("-u") + 1] == f"{os.getuid()}:{os.getgid()}"
    assert argv[argv.index("-v") + 1] == f"{tmp_path}:{tmp_path}"
    i = argv.index("img")
    assert argv[i + 1 :] == ["frama-c", *eva.arguments()]
    assert eva.command(tmp_path, "n", frama_c="/bin/fc") == [
        "/bin/fc",
        *eva.arguments(),
    ]


def fake(tmp_path, log, code=0, sleep=0, precision=eva.PRECISION):
    """An executable standing in for frama-c: it checks its arguments, waits `sleep` s,
    prints `log` and exits `code`."""
    (tmp_path / "fake.log").write_text(log)
    path = tmp_path / "frama-c"
    path.write_text(textwrap.dedent(f"""\
            #!{sys.executable}
            import pathlib, sys, time
            assert sys.argv[1:] == {eva.arguments(precision)!r}
            assert pathlib.Path("harness.c").is_file()
            time.sleep({sleep})
            sys.stdout.write(pathlib.Path({str(tmp_path / "fake.log")!r}).read_text())
            sys.exit({code})
            """))
    path.chmod(0o755)
    return str(path)


def test_run_writes_log_and_report(tmp_path):
    """A run writes the log and a report of the analysed C."""
    sources(tmp_path / "src")
    fc = fake(tmp_path, LOG)
    report = eva.run("t", tmp_path / "src", tmp_path / "out", 60, frama_c=fc)
    work = tmp_path / "out" / "t"
    assert (work / "eva.log").read_text() == LOG
    saved = json.loads((work / "report.json").read_text())
    assert saved == report
    assert report["count"] == 4 and report["tune"] == "t"
    assert report["source"] == eva.digest(tmp_path / "src" / "t.c")
    line = eva.summary(report)
    assert line.startswith("t: 4 alarms (2 accessing out of bounds index, ")
    assert "1 out of bounds read" in line and "trap reachable" in line


@pytest.mark.parametrize(
    "case, why",
    [
        ((LOG, 0, 5, 1), "timed out after 1 s"),
        ((LOG, 3, 0, 60), "frama-c exited 3"),
        ((HEAD, 0, 0, 60), "no analysis summary"),
    ],
)
def test_run_failures(tmp_path, case, why):
    """A timeout, a failed frama-c and a log with no summary each fail the tune."""
    log, code, sleep, timeout = case
    sources(tmp_path / "src")
    fc = fake(tmp_path, log, code, sleep)
    with pytest.raises(eva.EvaError, match=why):
        eva.run("t", tmp_path / "src", tmp_path / "out", timeout, frama_c=fc)


def test_metric_from_reports(tmp_path):
    """The metric reads each tune's report; a report of other C, or none, fails."""
    sources(tmp_path / "src")
    eva.run("t", tmp_path / "src", tmp_path / "out", 60, frama_c=fake(tmp_path, LOG))
    assert eva.metric(["t"], tmp_path / "src", tmp_path / "out") == {"t:alarms": 4}
    with pytest.raises(eva.EvaError, match="no report"):
        eva.metric(["u"], tmp_path / "src", tmp_path / "out")
    (tmp_path / "src" / "t.c").write_text("int y;\n")
    with pytest.raises(eva.EvaError, match="not of"):
        eva.metric(["t"], tmp_path / "src", tmp_path / "out")


def test_metric_rejects_failed_report(tmp_path):
    """A report of a run that failed is no count."""
    sources(tmp_path / "src")
    with pytest.raises(eva.EvaError):
        eva.run(
            "t", tmp_path / "src", tmp_path / "out", 60, frama_c=fake(tmp_path, LOG, 2)
        )
    with pytest.raises(eva.EvaError, match="exited 2"):
        eva.metric(["t"], tmp_path / "src", tmp_path / "out")


def test_main_runs_and_reports(tmp_path, capsys):
    """The CLI prints each tune's line and alarms, fails when any tune fails, and prints
    the metric as JSON."""
    sources(tmp_path / "src", "a")
    sources(tmp_path / "src", "b")
    dirs = ["--src", str(tmp_path / "src"), "--out", str(tmp_path / "out")]
    fc = ["--frama-c", fake(tmp_path, LOG)]
    assert eva.main(["a", "b", "-v", *dirs, *fc]) == 0
    out = capsys.readouterr().out
    assert "a: 4 alarms" in out and "b: 4 alarms" in out
    assert "t.c:69: accessing out of bounds index: (int)(0x789" in out
    assert eva.main(["a", "c", *dirs, *fc]) == 1
    assert "FAIL" in capsys.readouterr().err
    assert eva.main(["a", "b", "--metric", *dirs]) == 0
    assert json.loads(capsys.readouterr().out) == {"a:alarms": 4, "b:alarms": 4}
    assert eva.main(["z", "--metric", *dirs]) == 1


def test_ratchet_holds_alarms_exactly(tmp_path):
    """The `bounds` metric measures the tool's keys per tune, and one more alarm than its
    budget regresses: no tolerance."""
    sources(tmp_path / "src")
    eva.run("t", tmp_path / "src", tmp_path / "out", 60, frama_c=fake(tmp_path, LOG))
    metric = next(m for m in load(ROOT / "virtuous-cycles.toml") if m.name == "bounds")
    assert metric.budget == "budgets/bounds.json"
    dirs = f"--src {tmp_path / 'src'} --out {tmp_path / 'out'}"
    run = f"{metric.options['run']} t {dirs}"
    local = dataclasses.replace(metric, options={"run": run, "cwd": ROOT})
    assert measure([local], quiet=True) == {"bounds": {"t:alarms": 4.0}}
    assert metric.regressed("t:alarms", 4, 3) and not metric.regressed("t:alarms", 3, 3)


def test_budgets_cover_every_generated_tune():
    """The budget holds each generated tune's alarms, so none drops out of the ratchet."""
    budget = json.loads((ROOT / "budgets" / "bounds.json").read_text(encoding="utf-8"))
    assert budget["direction"] == "lower"
    assert set(budget["budgets"]) == {f"{t}:alarms" for t in eva.TUNES}


def test_metric_holds_only_the_default_precision(tmp_path):
    """A report at another precision counts other alarms, so the metric refuses it."""
    sources(tmp_path / "src")
    other = eva.PRECISION + 1
    fc = fake(tmp_path, LOG, precision=other)
    report = eva.run(
        "t", tmp_path / "src", tmp_path / "out", 60, frama_c=fc, precision=other
    )
    assert report["precision"] == other
    with pytest.raises(eva.EvaError, match=f"precision {other}"):
        eva.metric(["t"], tmp_path / "src", tmp_path / "out")
