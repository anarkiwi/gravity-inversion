"""Frama-C EVA bounds check of the generated C (docs/bounds.md).

Each tune's out/readability/<tune>.c under tools/eva_harness.c (init of any song, any number
of plays, any I/O read) writes out/eva/<tune>/eva.log and report.json; `--metric` prints the
`bounds` metric, `{"<tune>:alarms": count}`, from the reports of the current C.
"""

import argparse
import concurrent.futures
import hashlib
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import time
import uuid

from tqdm import tqdm

from prgsize import generated

ROOT = pathlib.Path(__file__).resolve().parent.parent
TUNES = tuple(d.name for d in generated(ROOT / "tunes"))
SRC = ROOT / "out" / "readability"
OUT = ROOT / "out" / "eva"
TEMPLATE = ROOT / "tools" / "eva_harness.c"
DRIVER = ROOT / "c64" / "driver.h"
IMAGE = "framac/frama-c:30.0"
PRECISION = 0
TIMEOUT = 900
CPUS = 2

ALARM = re.compile(
    r"^\[eva:alarm\] (?P<file>[^:\s]+):(?P<line>\d+): Warning: ?(?P<rest>.*)$"
)
SUMMARY = re.compile(r"^\s*(?P<n>\d+) alarms? generated by the analysis")
ERRORS = re.compile(r"^\s*by the (?P<who>.+?):\s+(?P<errors>\d+) errors?\s")
COVERAGE = re.compile(
    r"(?P<done>\d+) (?P<what>functions analyzed|statements reached)"
    r" \(out of (?P<of>\d+)\)"
)
FINAL = re.compile(r"^\[eva:final-states\] Values at end of function (?P<fn>\w+):$")
NONTERM = "NON TERMINATING FUNCTION"


class EvaError(RuntimeError):
    """An analysis that did not finish with a result: its count is not zero, it is none."""


def arguments(precision=PRECISION):
    """frama-c's arguments analysing harness.c at EVA `precision`."""
    return [
        "-machdep",
        "gcc_x86_32",
        "harness.c",
        "-eva",
        "-eva-precision",
        str(precision),
        "-eva-no-show-progress",
    ]


def harness(tune, template=TEMPLATE):
    """The harness C of `tune`: the template including <tune>.c."""
    text = pathlib.Path(template).read_text(encoding="utf-8")
    if "@TUNE@" not in text:
        raise ValueError(f"{template}: no @TUNE@ placeholder")
    return text.replace("@TUNE@", tune)


def digest(path):
    """sha256 of the file at `path`."""
    return hashlib.sha256(pathlib.Path(path).read_bytes()).hexdigest()


def stage(tune, src=SRC, out=OUT):
    """`out`/<tune>/ holding the harness, <tune>.c and .h from `src` and c64/driver.h."""
    src = pathlib.Path(src)
    work = pathlib.Path(out) / tune
    work.mkdir(parents=True, exist_ok=True)
    for name in (f"{tune}.c", f"{tune}.h"):
        if not (src / name).is_file():
            raise FileNotFoundError(f"{src / name}: not generated (make readability)")
        shutil.copyfile(src / name, work / name)
    shutil.copyfile(DRIVER, work / DRIVER.name)
    (work / "harness.c").write_text(harness(tune), encoding="utf-8")
    return work


def command(work, name, *, image=IMAGE, cpus=CPUS, frama_c=None, precision=PRECISION):
    """The argv analysing `work`'s harness: `frama_c` run in `work` when given, else a
    container `name` of `image` limited to `cpus` with `work` mounted at its own path.
    """
    if frama_c:
        return [frama_c, *arguments(precision)]
    work = pathlib.Path(work).resolve()
    return [
        "docker",
        "run",
        "--rm",
        "--name",
        name,
        f"--cpus={cpus}",
        "-u",
        f"{os.getuid()}:{os.getgid()}",
        "-e",
        "HOME=/tmp",
        "-v",
        f"{work}:{work}",
        "-w",
        str(work),
        image,
        "frama-c",
        *arguments(precision),
    ]


def alarms(lines):
    """Each `[eva:alarm]` of a log's lines as {file, line, kind, assertion}: the kind is the
    message before its assertion (``out of bounds read``), the assertion its predicate,
    whitespace collapsed."""
    found = []
    i = 0
    while i < len(lines):
        m = ALARM.match(lines[i])
        i += 1
        if not m:
            continue
        body = [m["rest"]]
        while i < len(lines) and lines[i].startswith("  "):
            body.append(lines[i])
            i += 1
        text = " ".join(" ".join(body).split())
        kind, _, assertion = text.partition("assert")
        found.append(
            {
                "file": m["file"],
                "line": int(m["line"]),
                "kind": kind.strip().rstrip("."),
                "assertion": assertion.strip().rstrip(";").strip(),
            }
        )
    return found


def final_states(lines):
    """{function: whether it terminates} of each function in the log's final states."""
    out = {}
    for i, line in enumerate(lines):
        m = FINAL.match(line)
        if m:
            nxt = lines[i + 1].strip() if i + 1 < len(lines) else ""
            out[m["fn"]] = nxt != NONTERM
    return out


def parse(text):
    """The report of an EVA log: alarms, the summary's count (None with no summary), errors
    per analyzer, coverage, whether trap is reached (its final state, abort's, never
    terminates) and whether tune_play returns."""
    lines = text.splitlines()
    report = {"alarms": alarms(lines), "count": None, "errors": {}, "coverage": {}}
    for line in lines:
        if m := SUMMARY.match(line):
            report["count"] = int(m["n"])
        elif m := ERRORS.match(line):
            report["errors"][m["who"]] = int(m["errors"])
        elif m := COVERAGE.search(line):
            report["coverage"][m["what"].split()[0]] = [int(m["done"]), int(m["of"])]
    states = final_states(lines)
    report["trap_reached"] = "trap" in states
    report["play_returns"] = states.get("tune_play", False)
    return report


def check(report):
    """Raise EvaError unless `report` is a complete analysis: a summary, no errors, the
    summary's count of the alarms listed, and tune_play returning (else any count is
    vacuous)."""
    if report["count"] is None:
        raise EvaError("no analysis summary")
    if any(report["errors"].values()):
        raise EvaError(f"errors: {report['errors']}")
    if report["count"] != len(report["alarms"]):
        raise EvaError(
            f"summary counts {report['count']} alarms, log lists {len(report['alarms'])}"
        )
    if not report["play_returns"]:
        raise EvaError("tune_play never returns")


def run(tune, src=SRC, out=OUT, timeout=TIMEOUT, **kw):
    """Analyse `tune` within `timeout` seconds, writing eva.log and report.json; the report.
    EvaError on a timeout, a failed run or an incomplete analysis."""
    work = stage(tune, src, out)
    name = f"gi-eva-{tune}-{uuid.uuid4().hex[:8]}"
    argv = command(work, name, **kw)
    log = work / "eva.log"
    start = time.monotonic()
    with open(log, "w", encoding="utf-8") as f:
        try:
            proc = subprocess.run(
                argv,
                cwd=work,
                stdout=f,
                stderr=subprocess.STDOUT,
                timeout=timeout,
                check=False,
            )
        except subprocess.TimeoutExpired as e:
            if argv[0] == "docker":
                subprocess.run(
                    ["docker", "rm", "-f", name], capture_output=True, check=False
                )
            raise EvaError(f"{tune}: timed out after {timeout} s ({log})") from e
    report = parse(log.read_text(encoding="utf-8"))
    report.update(
        tune=tune,
        source=digest(work / f"{tune}.c"),
        returncode=proc.returncode,
        precision=kw.get("precision", PRECISION),
        seconds=round(time.monotonic() - start, 1),
    )
    (work / "report.json").write_text(json.dumps(report, indent=1), encoding="utf-8")
    if proc.returncode:
        raise EvaError(f"{tune}: frama-c exited {proc.returncode} ({log})")
    try:
        check(report)
    except EvaError as e:
        raise EvaError(f"{tune}: {e} ({log})") from e
    return report


def metric(tunes=TUNES, src=SRC, out=OUT):
    """{"<tune>:alarms": count} from each tune's report.json; EvaError on a report missing,
    incomplete or of C other than `src`/<tune>.c."""
    got = {}
    for tune in tunes:
        path = pathlib.Path(out) / tune / "report.json"
        if not path.is_file():
            raise EvaError(f"{path}: no report (tools/eva.py {tune})")
        report = json.loads(path.read_text(encoding="utf-8"))
        c = pathlib.Path(src) / f"{tune}.c"
        if not c.is_file() or report["source"] != digest(c):
            raise EvaError(f"{path}: not of {c} (tools/eva.py {tune})")
        if report["returncode"]:
            raise EvaError(f"{path}: frama-c exited {report['returncode']}")
        if report["precision"] != PRECISION:
            raise EvaError(f"{path}: precision {report['precision']}, not {PRECISION}")
        check(report)
        got[f"{tune}:alarms"] = report["count"]
    return got


def summary(report):
    """One line of a tune's report: its alarms by kind and whether trap is reachable."""
    kinds = {}
    for a in report["alarms"]:
        kinds[a["kind"]] = kinds.get(a["kind"], 0) + 1
    kind = ", ".join(f"{n} {k}" for k, n in sorted(kinds.items()))
    trap = "reachable" if report["trap_reached"] else "unreachable"
    by = f" ({kind})" if kind else ""
    return (
        f"{report['tune']}: {report['count']} alarms{by}; trap {trap};"
        f" {report['seconds']} s"
    )


def analyse(tunes, args):
    """Run every tune in parallel with tqdm progress; 1 when any failed, else 0."""
    kw = {
        "image": args.image,
        "cpus": args.cpus,
        "frama_c": args.frama_c,
        "precision": args.precision,
    }
    failed = []
    with concurrent.futures.ThreadPoolExecutor(min(args.jobs, len(tunes))) as pool:
        jobs = [
            pool.submit(run, t, args.src, args.out, args.timeout, **kw) for t in tunes
        ]
        done = concurrent.futures.as_completed(jobs)
        for job in tqdm(done, total=len(jobs), desc="eva", unit="tune"):
            try:
                report = job.result()
            except (EvaError, FileNotFoundError) as e:
                failed.append(str(e))
                tqdm.write(f"FAIL {e}")
                continue
            tqdm.write(summary(report))
            if args.verbose:
                for a in report["alarms"]:
                    tqdm.write(
                        f"  {a['file']}:{a['line']}: {a['kind']}: {a['assertion']}"
                    )
            sys.stdout.flush()
    for f in failed:
        print(f"FAIL {f}", file=sys.stderr)
    return 1 if failed else 0


def main(argv=None):
    """CLI entry point: analyse tunes (default: all), or print the metric."""
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("tunes", nargs="*", help="tunes (default: every generated tune)")
    ap.add_argument("--src", type=pathlib.Path, default=SRC)
    ap.add_argument("--out", type=pathlib.Path, default=OUT)
    ap.add_argument("--timeout", type=int, default=TIMEOUT, help="seconds per tune")
    ap.add_argument("--image", default=IMAGE)
    ap.add_argument("--cpus", type=int, default=CPUS, help="CPUs per container")
    ap.add_argument(
        "--precision",
        type=int,
        default=PRECISION,
        help="EVA precision (the metric holds only the default's)",
    )
    ap.add_argument("--frama-c", help="run this frama-c directly, not in a container")
    ap.add_argument("-j", "--jobs", type=int, default=len(TUNES))
    ap.add_argument("--metric", action="store_true", help="print the bounds metric")
    ap.add_argument("-v", "--verbose", action="store_true", help="list each alarm")
    args = ap.parse_args(argv)
    tunes = args.tunes or list(TUNES)
    if not args.metric:
        return analyse(tunes, args)
    try:
        print(json.dumps(metric(tunes, args.src, args.out), indent=1))
    except EvaError as e:
        print(e, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
