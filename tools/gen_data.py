"""Generate commando_data.h from the assembled original PSID and its ACME labels."""

import argparse
import re

PSID_HEADER = 0x7C


def parse_labels(text):
    """Parse an ACME label dump into {name: address}."""
    return {
        m[1]: int(m[2], 16)
        for m in re.finditer(r"^\s*(\S+)\s*=\s*\$([0-9a-fA-F]+)", text, re.M)
    }


def load_psid(data):
    """Return (load address, payload) of a PSID file with in-file load address."""
    assert data[:4] == b"PSID", "not a PSID file"
    off = data[6] << 8 | data[7]
    return data[off] | data[off + 1] << 8, data[off + 2 :]


def c_bytes(data):
    """Format bytes as a C initializer list."""
    return ",".join(f"0x{b:02x}" for b in data)


def generate(psid, labels):
    """Return header text for the song data image."""
    load, image = load_psid(psid)
    end = load + len(image)

    def span(lo, hi):
        return image[lo - load : hi - load]

    org, freq = labels["_songdata"], labels["freqsl"]
    freq_end = labels["posoff"]
    defs = {
        "SONG_ORG": f"0x{org:04x}",
        "SONG_DATA": c_bytes(span(org, end)),
        "FREQ_LEN": str(freq_end - freq),
        "FREQ_TABLE": c_bytes(span(freq, freq_end)),
        "SID_OFFSETS": c_bytes(span(labels["sid"], labels["sid"] + 3)),
    }
    for name in ("songptrs", "songtempos", "patpl", "patph"):
        defs[name.upper()] = str(labels[name] - org)
    defs["INS"] = str(labels["ins_pwl"] - org)
    body = "".join(f"#define {k} {v}\n" for k, v in defs.items())
    return f"/* generated by tools/gen_data.py */\n{body}"


def main(argv=None):
    """CLI entry point."""
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("psid")
    ap.add_argument("labels")
    ap.add_argument("out")
    args = ap.parse_args(argv)
    with open(args.psid, "rb") as f:
        psid = f.read()
    with open(args.labels, encoding="ascii") as f:
        labels = parse_labels(f.read())
    with open(args.out, "w", encoding="ascii") as f:
        f.write(generate(psid, labels))


if __name__ == "__main__":
    main()
